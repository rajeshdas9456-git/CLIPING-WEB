/**
 * ClipForge AI - AI Captions & Subtitles Engine (English, Hindi, Bengali)
 */

window.SubtitlesModule = (function () {
  'use strict';

  let currentWords = [];

  function init() {
    bindEvents();
  }

  function bindEvents() {
    const btnSrt = document.getElementById('btnDownloadSRT');
    const btnVtt = document.getElementById('btnDownloadVTT');

    if (btnSrt) {
      btnSrt.addEventListener('click', () => downloadSubtitleFile('srt'));
    }
    if (btnVtt) {
      btnVtt.addEventListener('click', () => downloadSubtitleFile('vtt'));
    }
  }

  function loadTranscript(words) {
    currentWords = words || [];
    renderSubtitlesList();
  }

  function renderSubtitlesList() {
    const container = document.getElementById('subtitlesListContainer');
    if (!container) return;

    if (currentWords.length === 0) {
      container.innerHTML = `
        <div style="text-align:center;padding:30px;color:var(--text-muted);">
          <p>No captions loaded. Generate or select a clip to view word timings.</p>
        </div>
      `;
      return;
    }

    container.innerHTML = currentWords.map((w, idx) => `
      <div style="display:flex;align-items:center;justify-content:space-between;background:rgba(255,255,255,0.03);padding:8px 12px;border-radius:6px;border:1px solid var(--border-subtle);gap:10px;">
        <span style="font-family:var(--font-mono);font-size:11px;color:var(--accent-cyan);min-width:65px;">
          ${w.start.toFixed(1)}s - ${w.end.toFixed(1)}s
        </span>
        <input type="text" class="form-input" value="${escapeHtml(w.word)}" style="padding:4px 8px;font-size:12px;font-weight:700;" onchange="ClipForge.SubtitlesModule.updateWord(${idx}, this.value)">
        <button class="btn btn-icon btn-sm" onclick="ClipForge.SubtitlesModule.deleteWord(${idx})" title="Delete word" style="width:28px;height:28px;">
          <i class="fa-regular fa-trash-can" style="font-size:11px;"></i>
        </button>
      </div>
    `).join('');
  }

  function updateWord(index, newText) {
    if (currentWords[index]) {
      currentWords[index].word = newText;
      ClipForge.showToast('Caption text updated! 📝', 'info');
    }
  }

  function deleteWord(index) {
    currentWords.splice(index, 1);
    renderSubtitlesList();
  }

  function downloadSubtitleFile(format = 'srt') {
    if (currentWords.length === 0) {
      ClipForge.showToast('No subtitles available to export', 'error');
      return;
    }

    let content = '';
    if (format === 'srt') {
      content = generateSRT(currentWords);
    } else {
      content = generateVTT(currentWords);
    }

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `clipforge_subtitles.${format}`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    ClipForge.showToast(`Downloaded ${format.toUpperCase()} subtitle file! 📄`, 'success');
  }

  function generateSRT(words) {
    let srt = '';
    let counter = 1;
    // Group words in chunks of 4
    for (let i = 0; i < words.length; i += 4) {
      const chunk = words.slice(i, i + 4);
      const start = formatSrtTime(chunk[0].start);
      const end = formatSrtTime(chunk[chunk.length - 1].end);
      const text = chunk.map(c => c.word).join(' ');

      srt += `${counter}\n${start} --> ${end}\n${text}\n\n`;
      counter++;
    }
    return srt;
  }

  function generateVTT(words) {
    let vtt = 'WEBVTT - Generated by ClipForge AI\n\n';
    for (let i = 0; i < words.length; i += 4) {
      const chunk = words.slice(i, i + 4);
      const start = formatVttTime(chunk[0].start);
      const end = formatVttTime(chunk[chunk.length - 1].end);
      const text = chunk.map(c => c.word).join(' ');

      vtt += `${start} --> ${end}\n${text}\n\n`;
    }
    return vtt;
  }

  function formatSrtTime(seconds) {
    const hrs = Math.floor(seconds / 3600);
    const mins = Math.floor((seconds % 3600) / 60);
    const secs = Math.floor(seconds % 60);
    const ms = Math.floor((seconds % 1) * 1000);
    return `${pad(hrs, 2)}:${pad(mins, 2)}:${pad(secs, 2)},${pad(ms, 3)}`;
  }

  function formatVttTime(seconds) {
    const mins = Math.floor(seconds / 60);
    const secs = Math.floor(seconds % 60);
    const ms = Math.floor((seconds % 1) * 1000);
    return `${pad(mins, 2)}:${pad(secs, 2)}.${pad(ms, 3)}`;
  }

  function pad(num, size) {
    let s = num + '';
    while (s.length < size) s = '0' + s;
    return s;
  }

  function escapeHtml(str) {
    return (str || '').replace(/[&<>'"]/g, 
      tag => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', "'": '&#39;', '"': '&quot;' }[tag] || tag)
    );
  }

  return {
    init,
    loadTranscript,
    updateWord,
    deleteWord,
    downloadSubtitleFile
  };
})();
